async function seedCollection(name, data) {
  console.log(`\n📝 Seeding ${name}...`);
  
  try {
    // Delete existing documents
    const existingDocs = await getDocs(collection(db, name));
    for (const doc of existingDocs.docs) {
      await deleteDoc(doc.ref);
    }
    console.log(`  ✓ Cleared existing ${name}`);

    // Add new documents
    for (const item of data) {
      await addDoc(collection(db, name), item);
    }
    console.log(`  ✓ Added ${data.length} documents to ${name}`);
  } catch (error) {
    console.error(`  ✗ Error seeding ${name}:`, error.message);
    process.exit(1);
  }
}

async function main() {
  try {
    console.log('🚀 Starting Firebase seeding...\n');
    
    await seedCollection('courses', coursesData);
    await seedCollection('liveClasses', liveClassesData);
    await seedCollection('recordedVideos', recordedVideosData);

    console.log('\n✅ Firebase seeding completed successfully!');
    process.exit(0);
  } catch (error) {
    console.error('\n❌ Error:', error.message);
    process.exit(1);
  }
}

main();
